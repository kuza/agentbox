# Egress: what the agent reaches through squid, its only way out.
#
#   squid.conf                   squid settings and access rules, no hosts
#   egress.d/<name>.conf         host groups, shared (in git)
#   egress.local.d/<name>.conf   yours, ignored by git; wins over egress.d/
#
# AB_EGRESS in config.env lists the enabled groups; unset means
# EGRESS_DEFAULT, empty means none. An agent's own group (AGENT_EGRESS, set
# by agent_select) must be among them. The groups' hosts and the MCP modules'
# remote hosts (MCP_EGRESS) go into a file generated on every start and
# included by squid.conf.
#
# A group file is data, never run: one host per line, # starts a comment.
#   example.com          HTTPS to example.com (port 443)
#   .example.com         the same for example.com and all its subdomains
#   minio.example:9000   that host on that port only, HTTPS or plain HTTP
#
# Sourced by run.sh. Provides egress_init, egress_write_conf, egress_start
# and EGRESS_SQUID_CONF.

EGRESS_DIRS=("$SCRIPT_DIR/egress.local.d" "$SCRIPT_DIR/egress.d")
EGRESS_DEFAULT="anthropic openai pypi go"

# Enabled groups, read and checked. Run after mcp_check_secrets, which
# collects the modules' hosts (MCP_EGRESS_ALL), and after agent_select.
# Result: EGRESS_HOSTS, one "host[:port]" each.
egress_init() {
  local name d file line host seen=" " list="${AB_EGRESS-$EGRESS_DEFAULT}" n entry
  EGRESS_HOSTS=()
  for name in ${list//,/ }; do
    if [[ ! "$name" =~ ^[a-z0-9][a-z0-9-]*$ ]]; then
      echo "error: AB_EGRESS: invalid group name '$name'" >&2
      exit 2
    fi
    [[ "$seen" == *" $name "* ]] && continue
    seen+="$name "
    file=""
    for d in "${EGRESS_DIRS[@]}"; do
      if [[ -f "$d/$name.conf" ]]; then file="$d/$name.conf"; break; fi
    done
    if [[ -z "$file" ]]; then
      echo "error: AB_EGRESS: no group '$name' (looked for egress.local.d/$name.conf and egress.d/$name.conf)" >&2
      exit 2
    fi
    n=0
    while IFS= read -r line || [[ -n "$line" ]]; do
      n=$((n + 1))
      read -r host line <<<"${line%%#*}"
      [[ -z "$host" ]] && continue
      if [[ -n "$line" ]]; then
        echo "error: $file:$n: one host per line" >&2
        exit 2
      fi
      egress_check_host "$host" "$file:$n"
      EGRESS_HOSTS+=("${host,,}")
    done < "$file"
  done
  for name in ${AGENT_EGRESS[@]+"${AGENT_EGRESS[@]}"}; do
    if [[ "$seen" != *" $name "* ]]; then
      echo "error: $AGENT needs the egress group '$name'; add it to AB_EGRESS (README, Egress)" >&2
      exit 2
    fi
  done
  for entry in ${MCP_EGRESS_ALL[@]+"${MCP_EGRESS_ALL[@]}"}; do
    host="${entry%% *}"
    egress_check_host "$host" "MCP module '${entry#* }'"
    EGRESS_HOSTS+=("${host,,}")
  done
}

egress_check_host() {  # <host[:port]> <where, for the error>
  local label='[a-z0-9]([a-z0-9-]*[a-z0-9])?'
  if [[ ! "${1,,}" =~ ^\.?($label\.)*$label(:([1-9][0-9]{0,4}))?$ ]] \
     || (( 10#${BASH_REMATCH[5]:-1} > 65535 )); then
    echo "error: $2: '$1' is not a host name, .domain or host:port" >&2
    exit 2
  fi
}

# Writes the generated squid include into <cache>/agentbox: plain hosts join
# squid.conf's "allowed" list (port 443 for HTTPS); a host:port gets a rule
# of its own, for that port only.
egress_write_conf() {
  local dir="${XDG_CACHE_HOME:-$HOME/.cache}/agentbox" host conf i=0 seen=" "
  mkdir -p "$dir"
  conf="# Generated by run.sh from the egress groups (AB_EGRESS) and the MCP
# modules' hosts (AB_MCP). Edit those, not this file.
# squid.conf uses the acl \"allowed\", so it must exist even when nothing is
# enabled; .invalid is a reserved domain that never resolves.
acl allowed dstdomain .invalid"$'\n'
  for host in ${EGRESS_HOSTS[@]+"${EGRESS_HOSTS[@]}"}; do
    [[ "$seen" == *" $host "* ]] && continue
    seen+="$host "
    if [[ "$host" == *:* ]]; then
      i=$((i + 1))
      conf+="acl ab_host_$i dstdomain ${host%:*}"$'\n'
      conf+="acl ab_port_$i port ${host##*:}"$'\n'
      conf+="http_access allow ab_host_$i ab_port_$i"$'\n'
    else
      conf+="acl allowed dstdomain $host"$'\n'
    fi
  done
  EGRESS_SQUID_CONF="$dir/squid-allow.conf"
  write_file "$EGRESS_SQUID_CONF" "$conf"
}

# Egress proxy. When squid.conf or the generated hosts change, squid is
# recreated; open sessions lose egress for a moment.
egress_start() {
  local hash conf
  conf="$(sidecar_copy ab-egress "$SCRIPT_DIR/squid.conf")"
  hash="$(cat "$conf" "$EGRESS_SQUID_CONF" | sha256sum | cut -c1-16)"
  if [[ "$(podman inspect -f '{{index .Config.Labels "agentbox.egress"}}' ab-egress 2>/dev/null)" != "$hash" ]]; then
    podman rm -f -v ab-egress >/dev/null 2>&1 || true
  fi
  start_sidecar ab-egress \
    --network ab-internal --network ab-egress \
    --label "agentbox.egress=$hash" \
    -v "$conf:/etc/squid/squid.conf:ro,Z" \
    -v "$EGRESS_SQUID_CONF:/etc/squid/agentbox-allow.conf:ro,Z" \
    "$IMG_SQUID"
}
